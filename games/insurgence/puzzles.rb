#
# EV015 is NOT a Strength boulder, which is why nothing in the core saw it. It is a hand-built event with
# trigger "Player Touch" and a branch per facing:
#
#   * the FIRST bump after entering the map runs page 1, which sets its temp switch A and JUMPS the
#     boulder three tiles south, out of its alcove at 49,64 and down into the room at 49,67. Page 2 (the
#     real push logic) is gated on switch 21, whose name in the database is 's:tsOn?("A")' -- i.e. "this
#     event's temp switch A", so the drop is what arms it;
#   * after that each bump steps it ONE tile the way the player faces, if $game_map.passable? allows;
#   * and the win is a nested pair of script conditions on the west branch: facing left, with the boulder
#     at y <= 42 AND x <= 42, it goes into the lava, sets switch 150 and erases itself.
#
# The temp switch and the event's position are both inside Game_Map, so they SURVIVE a save and reload,
# but leaving the map puts the boulder back at 49,64 and the haul starts again.
#
# The table below is the whole thing solved offline against the map's own data: for every tile the
# boulder can reach, the tile to stand on, the direction to press, and the shoves remaining. It was
# produced by breadth-first search over (player tile, boulder tile) using the game's own rules --
# Game_Map#passable? (009_Game_Map_.rb:217), Game_Character#passableEx? (011_Game_Character_1.rb:142),
# and the four diagonal stair events at 52..53, 52..55, which move the player themselves when a blocked
# step fires their touch trigger -- then re-verified move by move from the first bump to the win.
#
# From the boulder's alcove that is 66 shoves. There is no shorter route: the search is exhaustive and
# minimises pushes. 64 of the states it can be shoved into have no route left at all, which is why the
# policy covers every tile rather than one line: a wrong shove is answered with the way back, and when
# there is none it says so, so she can walk out and reset the map instead of hunting for a way through.

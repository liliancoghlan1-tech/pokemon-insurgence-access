    WALK = 0
    SURF = 1
    DOOR = 2
    TESS = 3

    DIR_KEY = { 8 => :dir_up, 2 => :dir_down, 4 => :dir_left, 6 => :dir_right }
    DELTA = { 8 => [0, -1], 2 => [0, 1], 4 => [-1, 0], 6 => [1, 0] }

    def self.table(mid)
      @tables ||= {}
      return @tables[mid] if @tables[mid]
      raw = RAW[mid]
      return nil if raw.nil?
      bytes = raw.unpack("m")[0]
      t = {}
      i = 0
      while i + 7 <= bytes.length
        x, y, dk, nx, ny, left = bytes[i, 7].unpack("CCCCCv")
        t[x * 1000 + y] = [dk & 15, dk >> 4, nx, ny, left]
        i += 7
      end
      @tables[mid] = t
    rescue StandardError
      nil
    end

    def self.here
      [($game_map.map_id rescue nil), ($game_player.x rescue 0), ($game_player.y rescue 0)]
    end

    # Every plain press in the same direction, merged by following each row's next-tile link. A door press
    # in the same direction ends the leg; a surf launch or a Tesseract shift is never merged into one.
    def self.leg(t, px, py)
      r = t[px * 1000 + py]
      return 0 if r.nil?
      dir = r[0]
      n = 0
      guard = 0
      while r && r[0] == dir && (r[1] == WALK || r[1] == DOOR) && guard < 300
        guard += 1
        n += 1
        break if r[1] == DOOR
        r = t[r[2] * 1000 + r[3]]
      end
      n
    end

    def self.nearest(t, px, py)
      best = nil
      bestd = nil
      t.each_key do |k|
        d = (k / 1000 - px).abs + (k % 1000 - py).abs
        if bestd.nil? || d < bestd
          bestd = d
          best = k
        end
      end
      best.nil? ? nil : [best / 1000, best % 1000, bestd]
    end

    def self.dir_word(d)
      PokeAccess::I18n.t(DIR_KEY[d] || :dir_up)
    end

    # The walkthrough asks every frame, so the answer is worked out once per tile.
    def self.steps
      h = here
      return @steps_val if @steps_key == h && @steps_val
      @steps_key = h
      @steps_val = compute_steps(h[0], h[1], h[2])
    rescue StandardError
      []
    end

    def self.compute_steps(mid, px, py)
      t = table(mid)
      return [] if t.nil?
      r = t[px * 1000 + py]
      if r.nil?
        near = nearest(t, px, py)
        return [] if near.nil?
        return [PokeAccess::I18n.t(:vr_offroad,
                                   :where => PokeAccess::I18n.t(:laser_at, :x => near[0].to_s,
                                                                :y => near[1].to_s),
                                   :n => near[2].to_s)]
      end
      left = r[4].to_s
      case r[1]
      when TESS
        [PokeAccess::I18n.t(:cc_tess, :left => left)]
      when SURF
        [PokeAccess::I18n.t(:vr_surf, :dir => dir_word(r[0]), :left => left)]
      else
        [PokeAccess::I18n.t(:vr_leg, :n => leg(t, px, py).to_s, :dir => dir_word(r[0]), :left => left)]
      end
    rescue StandardError
      []
    end
  end
end

